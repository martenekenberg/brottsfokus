/** The English name for a Swedish label from the data files. Throws if there is none. */
export function dataLabel(sv: string, lang: Lang): string {
  if (lang === 'sv') return sv;
  const en = EN[sv];
  if (en === undefined) throw new Error(`No English name for "${sv}"`);
  return en;
}

